-- شغّل هذا الملف مرة واحدة في Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null unique,
  role text not null check (role in ('admin','teacher','student')),
  student_code text unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.student_decisions (
  id uuid primary key default gen_random_uuid(),
  decision_number bigint generated by default as identity unique,
  student_id uuid not null references public.profiles(id) on delete cascade,
  decision_type text not null check (decision_type in ('parent_summons','expulsion')),
  reason text not null,
  issued_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.exams (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  starts_at timestamptz,
  ends_at timestamptz,
  is_open boolean not null default false,
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create or replace function public.current_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.profiles where id=auth.uid() and is_active=true $$;

alter table public.profiles enable row level security;
alter table public.student_decisions enable row level security;
alter table public.exams enable row level security;

drop policy if exists "profile read self or staff" on public.profiles;
create policy "profile read self or staff" on public.profiles for select to authenticated
using (id=auth.uid() or public.current_role()='admin' or public.current_role()='teacher');
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for all to authenticated
using (public.current_role()='admin') with check (public.current_role()='admin');

drop policy if exists "decision read own or admin" on public.student_decisions;
create policy "decision read own or admin" on public.student_decisions for select to authenticated
using (student_id=auth.uid() or public.current_role()='admin');
drop policy if exists "admin issue decisions" on public.student_decisions;
create policy "admin issue decisions" on public.student_decisions for insert to authenticated
with check (public.current_role()='admin' and issued_by=auth.uid());

drop policy if exists "exam read open or staff" on public.exams;
create policy "exam read open or staff" on public.exams for select to authenticated
using ((public.current_role()='student' and is_open=true) or public.current_role() in ('admin','teacher'));
drop policy if exists "staff create exams" on public.exams;
create policy "staff create exams" on public.exams for insert to authenticated
with check (public.current_role() in ('admin','teacher') and created_by=auth.uid());
drop policy if exists "staff update exams" on public.exams;
create policy "staff update exams" on public.exams for update to authenticated
using (public.current_role() in ('admin','teacher')) with check (public.current_role() in ('admin','teacher'));

